const REPLACEMENTS = Object.fromEntries(
  Object.entries(TRANSLATIONS).map(([lang, entries]) => [
    lang,
    [...entries].sort(([left], [right]) => right.length - left.length)
  ])
);

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

export function localizeCatalogText(value, lang) {
  if (lang === 'ru' || !REPLACEMENTS[lang]) return String(value ?? '');

  return REPLACEMENTS[lang].reduce((text, [source, translated]) => {
    const pattern = new RegExp(`(^|[^\\p{L}])(${escapeRegExp(source)})(?=$|[^\\p{L}])`, 'giu');
    return text.replace(pattern, (_match, prefix) => `${prefix}${translated}`);
  }, String(value ?? '').replace(/(\d)(?=(?:мкм|мл|см|мм|шт\.))/giu, '$1 '));
}
