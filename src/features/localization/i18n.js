class I18nEngine {
  constructor() {
    this.currentLang = this.detectLanguage();
  }

  detectLanguage() {
    try {
      const urlParams = new URLSearchParams(window.location.search);
      const urlLang = urlParams.get('lang');
      if (urlLang && TRANSLATIONS[urlLang]) {
        return urlLang;
      }
      const saved = localStorage.getItem('muosir_lang');
      if (saved && TRANSLATIONS[saved]) {
        return saved;
      }
    } catch (e) {
      console.warn("Language detect error:", e);
    }
    return 'ru';
  }

  getLang() {
    return this.currentLang;
  }

  setLang(lang) {
    if (!TRANSLATIONS[lang]) return;
    this.currentLang = lang;
    try {
      localStorage.setItem('muosir_lang', lang);
    } catch (error) {
      console.warn('Language preference could not be saved:', error);
    }

    // Update html lang attribute
    document.documentElement.lang = lang;

    this.applyTranslations();
    this.updateActiveButtons();

    window.dispatchEvent(new CustomEvent('muosir_lang_changed', { detail: { lang } }));
  }

  translate(key) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.ru;
    return dict[key] || TRANSLATIONS.ru[key] || key;
  }

  applyTranslations() {
    document.documentElement.lang = this.currentLang;

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.translate(key);
      if (text) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = text;
        } else {
          el.textContent = text;
        }
      }
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
      el.setAttribute('aria-label', this.translate(el.getAttribute('data-i18n-aria-label')));
    });

    this.updateActiveButtons();
  }

  updateActiveButtons() {
    document.querySelectorAll('[data-lang-btn]').forEach(btn => {
      const bLang = btn.getAttribute('data-lang-btn');
      btn.classList.toggle('is-active', bLang === this.currentLang);
      btn.classList.remove('bg-blue-600', 'text-white', 'shadow-md', 'text-slate-400', 'hover:text-white');
    });
  }
}

window.muosirI18n = new I18nEngine();
